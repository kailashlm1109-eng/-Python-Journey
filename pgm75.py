n=input("Enter a vowel:")
if n=='A':
    print(n,"-APPLE")
elif n=='E':
    print(n,"-ELEPHANT")
elif n=='I':
    print(n,"-INK")
elif n=='O':
    print(n,"-OWL")
elif n=='U':
    print(n,"-UMBERLA")
else:
    print(n,"-not a vowel")
